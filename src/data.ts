export function parseCSV(csvText: string): Student[] {
  const lines = csvText.trim().split('\n');
  const result: Student[] = [];
  
  // Skip header line
  for (let i = 1; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;
    
    // Parse considering double-quoted values like "0,00" or just standard comma separated
    const cells: string[] = [];
    let currentCell = '';
    let insideQuote = false;
    
    for (let j = 0; j < line.length; j++) {
      const char = line[j];
      if (char === '"') {
        insideQuote = !insideQuote;
      } else if (char === ',' && !insideQuote) {
        cells.push(currentCell);
        currentCell = '';
      } else {
        currentCell += char;
      }
    }
    cells.push(currentCell);
    
    if (cells.length < 11) continue;
    
    const matricula = cells[0].trim();
    
    const getFloatValue = (val: string): number => {
      const cleaned = val.replace(',', '.').trim();
      const parsed = parseFloat(cleaned);
      return isNaN(parsed) ? 0 : parsed;
    };

    const av1Total = getFloatValue(cells[1]);
    const atividadeParcial2 = getFloatValue(cells[2]);
    const atividadeFinal2 = getFloatValue(cells[3]);
    const atividadeFinal2Pap = getFloatValue(cells[4]);
    const av2Total = getFloatValue(cells[5]);
    const atividadeAvaliativa3 = getFloatValue(cells[6]);
    const atividadeAvaliativa3Pap = getFloatValue(cells[7]);
    const atividadeExtra = getFloatValue(cells[8]);
    const av3Total = getFloatValue(cells[9]);
    const totalCurso = getFloatValue(cells[10]);

    // Apply strict academic rules specified by the user
    const mediaParcial = (av1Total + av2Total) / 2;
    const reprovadoParcial = mediaParcial < 4.0;
    
    // AV3 Total requires checking both standard and PAP
    let selectedAV3 = Math.max(atividadeAvaliativa3, atividadeAvaliativa3Pap);
    const calculatedAV3Total = selectedAV3 + atividadeExtra;
    
    // If skipped percurso, or if total is below 4.0
    const reprovadoAV3 = !reprovadoParcial && calculatedAV3Total < 4.0;
    
    // Total Curso rule: ((Média Parcial) + AV3 total) / 2
    const calculatedTotalCurso = (mediaParcial + calculatedAV3Total) / 2;
    
    let aprovadoFinal = false;
    let status: Student['status'] = 'Reprovado no Percurso';
    
    if (reprovadoParcial) {
      status = 'Reprovado no Percurso';
    } else if (calculatedAV3Total < 4.0) {
      status = 'Reprovado na AV3';
    } else if (calculatedTotalCurso < 5.0) {
      status = 'Reprovado por Média Final';
    } else {
      aprovadoFinal = true;
      status = 'Aprovado';
    }

    result.push({
      matricula,
      av1Total,
      atividadeParcial2,
      atividadeFinal2,
      atividadeFinal2Pap,
      av2Total,
      atividadeAvaliativa3,
      atividadeAvaliativa3Pap,
      atividadeExtra,
      av3Total: parseFloat(av3Total.toFixed(2)),
      totalCurso: parseFloat(totalCurso.toFixed(2)),
      mediaParcial: parseFloat(mediaParcial.toFixed(2)),
      reprovadoParcial,
      reprovadoAV3,
      aprovadoFinal,
      status
    });
  }
  
  return result;
}

